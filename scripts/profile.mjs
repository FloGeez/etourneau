// Generates the banner of the GitHub profile (FloGeez/FloGeez): the starling perched on the wire, in light and dark.
//   starling-light.svg, starling-dark.svg — copy them into the profile repository's assets/.
// The drawing comes from logo/etourneau-perche.svg, the joints (head pivot, skull, front beak) from starling/,
// the colours, the head's duration and its curve from tokens.json. GitHub shows the banner as an <img>: no CSS variable,
// no external file, so everything is written out in each file.
// Gestures from the guidelines' articulated starling: the head snaps back as the flock passes overhead, lifts the beak
// by 12°, snaps forward again; blinks of 140 ms (eye squashed to 10 %). The flock: the stroked wings of @flogeez/murmuration.
// Usage: npm run profile
import { readFileSync, writeFileSync } from 'node:fs';
import { PERCHED } from '../starling/starling.js';

const root = new URL('../', import.meta.url);
const j = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'));
const logo = readFileSync(new URL('logo/etourneau-perche.svg', root), 'utf8');

/* ——— The drawing: the perched logo's paths ——— */
const paths = [...logo.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
const [LEGS, , BODY, BELLY, WING, BEAK] = paths; // the second one is the clip path
if (paths.length !== 6 || BODY !== PERCHED.BODY || BELLY !== PERCHED.BELLY || BEAK !== PERCHED.BEAK) {
  throw new Error('etourneau-perche.svg no longer matches PERCHED in starling.js: update one or the other');
}
const circle = (k) => logo.match(/<circle ([^/]+)\/>/g)[k].match(/cx="[^"]+" cy="[^"]+" r="[^"]+"/)[0];
const EYE = circle(0), HIGHLIGHT = circle(1);

/* ——— The colours ——— */
const THEMES = Object.fromEntries(['light', 'dark'].map((name) => {
  const t = (k) => j.theme[name][k].$value;
  return [name, { body: t('logo-body'), wing: t('logo-wing'), belly: t('logo-belly'), beak: t('logo-beak'), ink: j.color.ink.$value,
    legs: t('legs'), wire: t('text'), birds: t('birds'), birds2: t('birds-2') }];
}));

const W = 800, H = 200, T = 14; // loop length in seconds
const pc = (t) => `${+(t / T * 100).toFixed(3)}%`;
const EASE = `cubic-bezier(${j.ease['in-out'].$value.join(', ')})`;
const SNAP = parseFloat(j.duration.flash.$value) / 1000; // a bird turns its head in one snap

// The wire: the guidelines' gentle sag, y = 168 + 24 t (1 − t)
const wireY = (x) => { const t = x / W; return 168 + 24 * t * (1 - t); };
const BX = 500, S = 0.8, BY = wireY(BX) + 0.6; // the bird's (104, 193) lands on the wire
const HEAD_X = BX + S * (PERCHED.HEAD_PIVOT[0] - 104);

/* ——— Timeline ——— */
const FLY = [3.0, 7.6], FX = [940, -130]; // the flock crosses right to left
const speed = (FX[0] - FX[1]) / (FLY[1] - FLY[0]);
const LOOK = FLY[0] + (FX[0] - HEAD_X) / speed + 0.05;
const LOOK_END = LOOK + 2.0;
const BLINKS = [1.4, 8.4, 11.2, 11.5];

const head = [[0, 0, 1], [LOOK, 0, 1, EASE], [LOOK + SNAP, 0, -1], [LOOK + .55, 0, -1, 'ease-in-out'], [LOOK + .925, 12, -1, 'ease-in-out'],
  [LOOK + 1.3, 0, -1], [LOOK_END, 0, -1, EASE], [LOOK_END + SNAP, 0, 1], [T, 0, 1]]
  .map(([t, a, d, e]) => `${pc(t)} { transform: rotate(${a}deg) scaleX(${d});${e ? ` animation-timing-function: ${e};` : ''} }`).join('\n    ');
// the profile beak fades out and the front beak shows for an instant mid-snap (beakOpacities in starling.js)
const snapAt = (t0, u) => t0 + SNAP * u;
const opacities = (keys) => keys.map(([t, o]) => `${pc(t)} { opacity: ${o}; }`).join(' ');
const profile = opacities([[0, 1], ...[LOOK, LOOK_END].flatMap((t0) => [[snapAt(t0, .417), 1], [snapAt(t0, .479), 0], [snapAt(t0, .521), 0], [snapAt(t0, .583), 1]]), [T, 1]]);
const front = opacities([[0, 0], ...[LOOK, LOOK_END].flatMap((t0) => [[snapAt(t0, .422), 0], [snapAt(t0, .5), 1], [snapAt(t0, .578), 0]]), [T, 0]]);
const blink = ['0% { transform: scaleY(1); }', ...BLINKS.flatMap((t) => [
  `${pc(t)} { transform: scaleY(1); animation-timing-function: ease-in; }`,
  `${pc(t + .07)} { transform: scaleY(.1); animation-timing-function: ease-out; }`,
  `${pc(t + .14)} { transform: scaleY(1); }`]), '100% { transform: scaleY(1); }'].join('\n    ');

/* ——— The flock ——— */
// [dx, dy, colour (0 | 1), flap phase in s, bob delay in s]
const FLOCK = [[0, 0, 0, 0, 0], [-26, -11, 1, .11, -.6], [20, -16, 0, .23, -1.1], [-46, 5, 0, .07, -.3], [38, 7, 1, .3, -1.6], [-16, 15, 1, .17, -.9], [58, -5, 0, .26, -1.3]];
const wingsPath = (w) => `M-7.5 ${w}Q-3.6 -1.8 0 1.35Q3.6 -1.8 7.5 ${w}`; // the engine's wings, × 1.5
// SMIL: the only way to morph a path in every browser; hidden with the flock when motion is reduced
const flap = `<animate attributeName="d" dur="0.39s" repeatCount="indefinite" calcMode="spline" keyTimes="0;0.5;1" keySplines="0.45 0 0.55 1;0.45 0 0.55 1" values="${wingsPath(3.6)};${wingsPath(-3.6)};${wingsPath(3.6)}"`;

const svg = (c) => `<!-- Generated by scripts/profile.mjs (npm run profile): do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" fill="none">
  <style>
    .head, .eye, .fx, .fy, .bob { transform-box: view-box; }
    .head { transform-origin: ${PERCHED.HEAD_PIVOT[0]}px ${PERCHED.HEAD_PIVOT[1]}px; animation: head ${T}s infinite; }
    .eye { transform-origin: ${PERCHED.EYE.cx}px ${PERCHED.EYE.cy}px; animation: blink ${T}s infinite; }
    .beak { animation: profile ${T}s infinite linear; }
    .beak-front { opacity: 0; animation: front ${T}s infinite linear; }
    .fx { transform-origin: 0 0; transform: translateX(${FX[0]}px); animation: fx ${T}s infinite linear; }
    .fy { transform-origin: 0 0; animation: fy ${T}s infinite; }
    .bob { transform-origin: 0 0; animation: bob 1.9s infinite ease-in-out alternate; }
    .flock path { stroke-width: 2.4; stroke-linecap: round; stroke-linejoin: round; fill: none; opacity: .95; }
    @keyframes head {
    ${head}
    }
    @keyframes profile { ${profile} }
    @keyframes front { ${front} }
    @keyframes blink {
    ${blink}
    }
    @keyframes fx { 0%, ${pc(FLY[0])} { transform: translateX(${FX[0]}px); } ${pc(FLY[1])}, 100% { transform: translateX(${FX[1]}px); } }
    @keyframes fy { 0%, ${pc(FLY[0])} { transform: translateY(78px); animation-timing-function: ease-out; } ${pc((FLY[0] + FLY[1]) / 2)} { transform: translateY(30px); animation-timing-function: ease-in; } ${pc(FLY[1])}, 100% { transform: translateY(54px); } }
    @keyframes bob { from { transform: translateY(-3px); } to { transform: translateY(3px); } }
    @media (prefers-reduced-motion: reduce) {
      *, *::before, *::after { animation: none !important; }
      .flock { display: none; }
    }
  </style>
  <path d="M0 ${wireY(0)} Q${W / 2} ${168 + 12} ${W} ${wireY(W)}" stroke="${c.wire}" stroke-width="2" stroke-linecap="round"/>
  <g transform="translate(${BX} ${BY.toFixed(2)}) scale(${S}) translate(-104 -193)">
    <path d="${LEGS}" stroke="${c.legs}" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round"/>
    <clipPath id="a"><path d="${BODY}"/></clipPath>
    <path d="${BODY}" fill="${c.body}"/>
    <g class="head"><circle cx="${PERCHED.SKULL.cx}" cy="${PERCHED.SKULL.cy}" r="${PERCHED.SKULL.rx}" fill="${c.body}"/></g>
    <g clip-path="url(#a)"><path d="${BELLY}" fill="${c.belly}"/><path d="${WING}" fill="${c.wing}"/></g>
    <g class="head">
      <path class="beak" d="${BEAK}" fill="${c.beak}"/>
      <path class="beak-front" d="${PERCHED.BEAK_FRONT}" fill="${c.beak}"/>
      <g class="eye"><circle ${EYE} fill="${c.ink}"/><circle ${HIGHLIGHT} fill="${c.belly}"/></g>
    </g>
  </g>
  <g class="flock"><g class="fx"><g class="fy">
      ${FLOCK.map(([dx, dy, k, ph, bob]) => `<g transform="translate(${dx} ${dy})"><g class="bob" style="animation-delay:${bob}s"><path stroke="${k ? c.birds2 : c.birds}" d="${wingsPath(3.6)}">${flap} begin="-${ph}s"/></path></g></g>`).join('\n      ')}
  </g></g></g>
</svg>
`;

for (const [name, colours] of Object.entries(THEMES)) writeFileSync(new URL(`profile/starling-${name}.svg`, root), svg(colours));
console.log('profile/starling-light.svg and profile/starling-dark.svg generated: copy them into FloGeez/FloGeez, assets/.');
